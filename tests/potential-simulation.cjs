const assert=require('node:assert/strict'),sim=require('../potential-simulation.js');
const period={year:2026,month:10},raw={address:'Blok M Plaza',kabupaten:'Jakarta Selatan'};
const a=sim.suggest(raw,'Kuliner',period);
assert.equal(a.inputs.locationType,'shopping');assert(a.inputs.weekendVisitors>a.inputs.weekdayVisitors);
assert.equal(sim.location({address:'Gedung perkantoran ABC'}).type,'office');
assert.equal(sim.location({kabupaten:'Jakarta Selatan'}).type,'neutral');
assert.equal(sim.location({address:'Office mall'}).type,'neutral');
const all=sim.calendar(2026,10,[0,1,2,3,4,5,6]);assert.equal(all.weekday+all.weekend,304);
assert.equal(sim.calendar(2024,2,[0,1,2,3,4,5,6]).weekday+sim.calendar(2024,2,[0,1,2,3,4,5,6]).weekend,60);
const test=sim.suggest({},'Kuliner',{year:2026,month:1},{weekdayVisitors:10,weekendVisitors:20,ticket:10000,share:50,units:1,openDays:[0,1,2,3,4,5,6]});
assert.equal(test.days.weekday,22);assert.equal(test.days.weekend,9);
assert.equal(test.cashflowYtd,4000000);assert.equal(test.ytd,2000000);
assert.equal(sim.suggest({},'Kuliner',period,{openDays:[]}).ytd,0);
assert.equal(sim.effective({},'Kuliner',period,{basis:'real',realRevenue:100}).ytd,1000);
assert.equal(sim.effective({},'Kuliner',period,{basis:'assumption',visitors:0,avgTicket:0}).ytd,0);
assert.equal(sim.effective({},'Kuliner',period).simulated,true);
assert.equal(sim.suggest({},'Kuliner',{year:2026,month:1}).cashflowYtd,sim.suggest({},'Kuliner',{year:2026,month:1}).cashflowMonthly);
assert.equal(sim.suggest({},'Kuliner',period,{share:0}).ytd,0);
assert.throws(()=>sim.calendar(2026,13,[1]),/Periode/);
const snapshot=JSON.stringify(raw);sim.suggest(raw,'Kuliner',period);assert.equal(JSON.stringify(raw),snapshot);
console.log('Simulation: calendar YTD, leap year, location hints, capture share, zero and manual precedence passed.');
const one=sim.suggest({totals:{edc:1},mids:[{mid:'a'}]},'Kuliner',period);
const five=sim.suggest({totals:{edc:5},mids:[{mid:'a'},{mid:'b'}]},'Kuliner',period,{units:999});
assert.equal(five.inputs.units,5);assert.equal(five.ytd,one.ytd*5);
assert.equal(five.machineBased,true);
assert.equal(sim.suggest({totals:{edc:0},mids:[]},'Kuliner',period).ytd,null);
assert.equal(sim.suggest({mids:[{mid:'a'}]},'Kuliner',period).ytd,null);
assert.equal(sim.effective({totals:{edc:5}},'Kuliner',period,{basis:'real',realRevenue:100}).ytd,1000);
assert.equal(sim.suggest({store_name:'Livin'},'Kuliner',period).inputs.units,1);
console.log('EDC: terminal count multiplier, ignore MID count/stale units, missing machines and manual/Livin preservation passed.');
